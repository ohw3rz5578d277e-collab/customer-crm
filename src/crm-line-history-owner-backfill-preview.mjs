import { createHash } from 'node:crypto';

const CUSTOMER_ID_RE=/^\d{8}$/;
const LINE_ID_RE=/^U[0-9a-fA-F]{20,}$/;

function text(v){return v==null?'':String(v).trim()}
function sha16(v){return createHash('sha256').update(text(v)).digest('hex').slice(0,16)}
function sqlText(v){return "'"+String(v??'').replaceAll('\u0000','').replaceAll("'","''")+"'"}

function normalizeCandidate(r){
  return {
    message_key:text(r.message_key??r.messageKey??r.msgKey??r.message_id),
    line_user_id:text(r.line_user_id??r.lineUserId),
    direction:text(r.direction),
    message_type:text(r.message_type??r.messageType)||'text',
    message_text:String(r.message_text??r.content??r.text??''),
    sender_name:text(r.sender_name??r.name),
    sent_at:text(r.sent_at??r.timestamp),
    source:text(r.source),
    source_row:Number(r.source_row??r.csv_row_no??r.line??0)||0
  };
}

function fingerprint(r){
  return [
    r.target_customer_id,
    r.line_user_id,
    r.direction,
    r.sent_at,
    r.message_text
  ].join('\u0000');
}

function buildPreviewSql(rows){
  const out=[
    '-- READ ONLY. Generated by crm-line-history-owner-backfill-preview.mjs',
    '-- Owner decisions are mapped to exact existing Customer IDs locally.',
    '-- This preview never INSERTs or UPDATEs. It only measures target validity, existing rows, and would_insert.',
    '-- Do not convert this file into a write operation.',
    ''
  ];
  const CHUNK=75;
  for(let offset=0;offset<rows.length;offset+=CHUNK){
    const chunk=rows.slice(offset,offset+CHUNK);
    const values=chunk.map(x=>[
      sqlText(x.message_key),
      sqlText(x.target_customer_id),
      sqlText(x.line_user_id),
      sqlText(x.direction),
      sqlText(x.sent_at),
      sqlText(x.message_text),
      x.batch_duplicate?1:0
    ].join(',')).map(x=>'('+x+')').join(',\n');

    out.push(`WITH candidates(message_key,target_customer_id,line_user_id,direction,sent_at,message_text,batch_duplicate) AS (VALUES
${values}
)
SELECT ${Math.floor(offset/CHUNK)+1} AS chunk_no,
  COUNT(*) AS candidate_rows,
  SUM(CASE WHEN batch_duplicate=1 THEN 1 ELSE 0 END) AS batch_duplicate_rows,
  SUM(CASE WHEN NOT EXISTS(
    SELECT 1 FROM customers c
    WHERE c.customer_id=candidates.target_customer_id
      AND COALESCE(c.deleted_at,'')=''
  ) THEN 1 ELSE 0 END) AS target_missing_rows,
  SUM(CASE WHEN EXISTS(
    SELECT 1 FROM customers c
    WHERE c.customer_id=candidates.target_customer_id
      AND COALESCE(c.deleted_at,'')=''
      AND COALESCE(c.line_user_id,'')<>''
      AND COALESCE(c.line_user_id,'')<>candidates.line_user_id
  ) THEN 1 ELSE 0 END) AS target_line_conflict_rows,
  SUM(CASE WHEN EXISTS(
    SELECT 1 FROM customers c
    WHERE c.customer_id=candidates.target_customer_id
      AND COALESCE(c.deleted_at,'')=''
      AND (COALESCE(c.line_user_id,'')='' OR COALESCE(c.line_user_id,'')=candidates.line_user_id)
  ) AND EXISTS(
    SELECT 1 FROM customer_line_messages m
    WHERE m.message_key=candidates.message_key
       OR (
         m.customer_id=candidates.target_customer_id
         AND COALESCE(m.line_user_id,'')=candidates.line_user_id
         AND m.direction=candidates.direction
         AND m.sent_at=candidates.sent_at
         AND m.message_text=candidates.message_text
       )
  ) THEN 1 ELSE 0 END) AS already_present_rows,
  SUM(CASE WHEN batch_duplicate=0
    AND EXISTS(
      SELECT 1 FROM customers c
      WHERE c.customer_id=candidates.target_customer_id
        AND COALESCE(c.deleted_at,'')=''
        AND (COALESCE(c.line_user_id,'')='' OR COALESCE(c.line_user_id,'')=candidates.line_user_id)
    )
    AND NOT EXISTS(
      SELECT 1 FROM customer_line_messages m
      WHERE m.message_key=candidates.message_key
         OR (
           m.customer_id=candidates.target_customer_id
           AND COALESCE(m.line_user_id,'')=candidates.line_user_id
           AND m.direction=candidates.direction
           AND m.sent_at=candidates.sent_at
           AND m.message_text=candidates.message_text
         )
    )
  THEN 1 ELSE 0 END) AS would_insert_rows
FROM candidates;`);
  }
  return out.join('\n\n')+'\n';
}

export function buildLineHistoryOwnerBackfillReadonlyPreview({plan={},candidates=[]}={}){
  const errors=[];
  const actions=Array.isArray(plan.proposed_actions)?plan.proposed_actions:[];
  const normalized=(candidates||[]).map(normalizeCandidate);

  if(text(plan.planner)!=='line_history_owner_decision_plan_v1')errors.push({code:'PLAN_FORMAT_INVALID'});
  if(Number(plan.validation_error_count||0)!==0)errors.push({code:'PLAN_VALIDATION_ERRORS_PRESENT'});
  if(plan.authorization_granted===true)errors.push({code:'PLAN_ALREADY_AUTHORIZED'});
  if(Number(plan.proposed_write_actions||0)!==0)errors.push({code:'PLAN_PHYSICAL_WRITE_COUNT_MUST_BE_ZERO'});
  if(plan.ready_for_readonly_backfill_preview!==true&&actions.length>0)errors.push({code:'PLAN_NOT_READY_FOR_READONLY_PREVIEW'});

  const selected=[];
  const selectedMessageKeys=new Map();

  for(const action of actions){
    const queueId=text(action.queue_id);
    const target=text(action.target_customer_id);
    const line=text(action.line_user_id);
    const expectedHash=text(action.source_line_id_hash);
    const expectedRows=Number(action.message_rows||0);

    if(text(action.action)!=='BACKFILL_LINE_HISTORY_TO_EXISTING_CUSTOMER'){
      errors.push({queue_id:queueId,code:'ACTION_TYPE_INVALID'});
      continue;
    }
    if(!CUSTOMER_ID_RE.test(target)){
      errors.push({queue_id:queueId,code:'TARGET_CUSTOMER_ID_INVALID'});
      continue;
    }
    if(!LINE_ID_RE.test(line)){
      errors.push({queue_id:queueId,code:'LINE_USER_ID_INVALID'});
      continue;
    }
    if(expectedHash!==sha16(line)){
      errors.push({queue_id:queueId,code:'SOURCE_LINE_HASH_MISMATCH'});
      continue;
    }
    if(expectedRows<1){
      errors.push({queue_id:queueId,code:'EXPECTED_MESSAGE_ROWS_INVALID'});
      continue;
    }

    const matches=normalized.filter(x=>x.line_user_id===line);
    if(matches.length!==expectedRows){
      errors.push({
        queue_id:queueId,
        code:'CANDIDATE_MESSAGE_COUNT_MISMATCH',
        expected_rows:expectedRows,
        actual_rows:matches.length
      });
      continue;
    }

    for(const row of matches){
      if(!row.message_key||!row.direction||!row.sent_at||!row.message_text){
        errors.push({queue_id:queueId,code:'CANDIDATE_REQUIRED_FIELD_MISSING'});
        continue;
      }
      if(selectedMessageKeys.has(row.message_key)){
        const priorTarget=selectedMessageKeys.get(row.message_key);
        if(priorTarget!==target){
          errors.push({queue_id:queueId,code:'CANDIDATE_SELECTED_MULTIPLE_TARGETS'});
        }
        continue;
      }
      selectedMessageKeys.set(row.message_key,target);
      selected.push({
        ...row,
        queue_id:queueId,
        target_customer_id:target
      });
    }
  }

  const seenFingerprints=new Map();
  const rows=selected.map(x=>{
    const fp=fingerprint(x);
    const duplicateOf=seenFingerprints.get(fp)||'';
    if(!duplicateOf)seenFingerprints.set(fp,x.message_key);
    return {
      ...x,
      batch_duplicate:Boolean(duplicateOf),
      batch_duplicate_of_message_key:duplicateOf
    };
  });

  const previewSql=errors.length?'' : buildPreviewSql(rows);

  return {
    planner:'line_history_owner_backfill_readonly_preview_v1',
    source_identity_actions:actions.length,
    selected_candidate_rows:rows.length,
    batch_duplicate_rows:rows.filter(x=>x.batch_duplicate).length,
    preview_candidate_rows:rows.filter(x=>!x.batch_duplicate).length,
    validation_error_count:errors.length,
    validation_errors:errors,
    preview_ready:errors.length===0&&rows.length>0,
    private_rows:rows,
    preview_sql:previewSql,
    safety:{
      production_d1_read:0,
      production_d1_write:0,
      sql_generated:errors.length===0&&rows.length>0,
      generated_sql_read_only:true,
      write_sql_generated:false,
      customer_id_generation:0,
      customer_update:0,
      customer_delete:0,
      customer_merge:0,
      line_send:0,
      worker_deploy:0,
      production_deploy:0
    }
  };
}
