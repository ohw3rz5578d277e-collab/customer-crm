import fs from 'node:fs';
import path from 'node:path';
import { parseLineLogCsv, parseCustomerMasterCsv, resolveLineHistoryRows } from '../src/crm-line-history-sheet-backfill.mjs';

function arg(name){const i=process.argv.indexOf(name);return i>=0?String(process.argv[i+1]||''):''}
const linePath=arg('--line-log');
const masterPath=arg('--customer-master');
const outDir=arg('--out-dir')||'artifacts/line-history-backfill';
if(!linePath||!masterPath){console.error('Usage: node scripts/prepare-line-history-sheet-backfill.mjs --line-log LINE_log.csv --customer-master Customer_Master.csv [--out-dir DIR]');process.exit(2)}

function read(file){return fs.readFileSync(file,'utf8')}
function sqlText(v){return "'"+String(v??'').replaceAll('\u0000','').replaceAll("'","''")+"'"}
function sqlNullable(v){return String(v??'').trim()?sqlText(v):'NULL'}
function countReasons(items){const out={};for(const x of items||[])out[x.reason]=(out[x.reason]||0)+1;return out}
function countMatchSources(items){const out={};for(const x of items||[])out[x.match_source]=(out[x.match_source]||0)+1;return out}

const lineCsv=read(linePath),masterCsv=read(masterPath);
const parsed=parseLineLogCsv(lineCsv),master=parseCustomerMasterCsv(masterCsv);
const masterAsCrm=master.entries.map(x=>({customer_id:x.customer_id,line_user_id:x.line_user_id,name:x.name,line_display_name:x.line_name}));
const resolved=await resolveLineHistoryRows(parsed,master,masterAsCrm);
if(resolved.conflicts.length){
  console.error('RESULT=LINE_HISTORY_BACKFILL_IDENTITY_CONFLICT');
  console.error(JSON.stringify(resolved.conflicts.slice(0,30),null,2));
  process.exit(3);
}
if(!resolved.candidates.length){console.error('RESULT=LINE_HISTORY_BACKFILL_NO_CANDIDATES');process.exit(4)}

fs.mkdirSync(outDir,{recursive:true});
const previewPath=path.join(outDir,'line-history-backfill-preview.sql');
const commitPath=path.join(outDir,'line-history-backfill-commit.sql');
const summaryPath=path.join(outDir,'line-history-backfill-summary.json');

const preview=[];
preview.push('-- READ ONLY. Generated by prepare-line-history-sheet-backfill.mjs');
preview.push('-- This file must not contain INSERT/UPDATE/DELETE/CREATE/ALTER/DROP.');
const CHUNK=100;
for(let offset=0;offset<resolved.candidates.length;offset+=CHUNK){
  const chunk=resolved.candidates.slice(offset,offset+CHUNK),values=chunk.map(x=>`(${sqlText(x.message_key)},${sqlText(x.customer_id)},${sqlText(x.line_user_id||'')},${sqlText(x.direction)},${sqlText(x.sent_at)},${sqlText(x.message_text)})`).join(',\n');
  preview.push(`\nWITH candidates(message_key,customer_id,line_user_id,direction,sent_at,message_text) AS (VALUES\n${values}\n)\nSELECT ${Math.floor(offset/CHUNK)+1} AS chunk_no, COUNT(*) AS candidate_rows,\n  SUM(CASE WHEN EXISTS(SELECT 1 FROM customers c WHERE c.customer_id=candidates.customer_id) THEN 1 ELSE 0 END) AS crm_customer_matched,\n  SUM(CASE WHEN NOT EXISTS(SELECT 1 FROM customers c WHERE c.customer_id=candidates.customer_id) THEN 1 ELSE 0 END) AS crm_customer_missing,\n  SUM(CASE WHEN EXISTS(SELECT 1 FROM customer_line_messages m WHERE m.message_key=candidates.message_key OR (m.customer_id=candidates.customer_id AND COALESCE(m.line_user_id,'')=candidates.line_user_id AND m.direction=candidates.direction AND m.sent_at=candidates.sent_at AND m.message_text=candidates.message_text)) THEN 1 ELSE 0 END) AS already_present,\n  SUM(CASE WHEN EXISTS(SELECT 1 FROM customers c WHERE c.customer_id=candidates.customer_id) AND NOT EXISTS(SELECT 1 FROM customer_line_messages m WHERE m.message_key=candidates.message_key OR (m.customer_id=candidates.customer_id AND COALESCE(m.line_user_id,'')=candidates.line_user_id AND m.direction=candidates.direction AND m.sent_at=candidates.sent_at AND m.message_text=candidates.message_text)) THEN 1 ELSE 0 END) AS would_insert\nFROM candidates;`);
}
fs.writeFileSync(previewPath,preview.join('\n')+'\n');

const commit=[];
commit.push('-- WRITE FILE. DO NOT RUN WITHOUT FRESH OWNER APPROVAL.');
commit.push('-- INSERT ONLY. No customer creation/update/delete. Idempotent by message_key + exact fingerprint.');
for(const x of resolved.candidates){
  const raw=JSON.stringify({source:'line_history_sheet_backfill',match_source:x.match_source,source_row:x.source_row,csv_file_name:x.csv_file_name||null,csv_row_no:x.csv_row_no||null,source_kind:x.source||null,media_url:x.media_url||null});
  commit.push(`INSERT OR IGNORE INTO customer_line_messages (message_key,customer_id,line_user_id,direction,message_type,message_text,sender_name,sent_at,raw_json,created_at)\nSELECT ${sqlText(x.message_key)},${sqlText(x.customer_id)},${sqlNullable(x.line_user_id)},${sqlText(x.direction)},${sqlText(x.message_type||'text')},${sqlText(x.message_text)},${sqlNullable(x.sender_name)},${sqlText(x.sent_at)},${sqlText(raw)},datetime('now')\nWHERE EXISTS (SELECT 1 FROM customers c WHERE c.customer_id=${sqlText(x.customer_id)})\n  AND NOT EXISTS (SELECT 1 FROM customer_line_messages m WHERE m.message_key=${sqlText(x.message_key)} OR (m.customer_id=${sqlText(x.customer_id)} AND COALESCE(m.line_user_id,'')=${sqlText(x.line_user_id||'')} AND m.direction=${sqlText(x.direction)} AND m.sent_at=${sqlText(x.sent_at)} AND m.message_text=${sqlText(x.message_text)}));`);
}
fs.writeFileSync(commitPath,commit.join('\n\n')+'\n');

const summary={
  generated_at:new Date().toISOString(),
  source:{line_log:path.basename(linePath),customer_master:path.basename(masterPath)},
  line_log_rows:parsed.row_count,
  parsed_message_rows:parsed.rows.length,
  customer_master_rows:master.row_count,
  customer_master_valid_entries:master.entries.length,
  candidate_rows:resolved.candidates.length,
  skipped_rows:resolved.skipped.length,
  skipped_reasons:countReasons(resolved.skipped),
  match_sources:countMatchSources(resolved.candidates),
  conflict_rows:resolved.conflicts.length,
  safety:{production_d1_write:0,customer_id_generation:0,customer_update:0,customer_delete:0,line_send:0,commit_requires_owner_approval:true},
  files:{preview_sql:previewPath,commit_sql:commitPath}
};
fs.writeFileSync(summaryPath,JSON.stringify(summary,null,2)+'\n');

const previewSource=fs.readFileSync(previewPath,'utf8');
if(/\b(?:INSERT|UPDATE|DELETE|CREATE|ALTER|DROP|REPLACE|TRUNCATE)\b/i.test(previewSource.replace(/^--.*$/gm,'')))throw new Error('preview_sql_not_read_only');
const commitSource=fs.readFileSync(commitPath,'utf8');
if(/\b(?:UPDATE|DELETE|CREATE|ALTER|DROP|REPLACE|TRUNCATE)\b/i.test(commitSource.replace(/^--.*$/gm,'')))throw new Error('commit_sql_contains_forbidden_write');
if(/INSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+customers\b/i.test(commitSource))throw new Error('customer_insert_forbidden');

console.log(JSON.stringify(summary,null,2));
console.log('RESULT=LINE_HISTORY_BACKFILL_PLAN_READY');
console.log('PRODUCTION_D1_WRITE=0');
console.log('CUSTOMER_ID_GENERATION=0');
console.log('CUSTOMER_UPDATE=0');
console.log('CUSTOMER_DELETE=0');
console.log('LINE_SEND=0');
